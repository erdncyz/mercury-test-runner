  const ATTRIBUTES = ["placeholder", "aria-label", "title", "alt"];

  let lang = DEFAULT_LANG;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGS[saved]) lang = saved;
  } catch { /* storage may be blocked; keep the default */ }

  function format(template, params) {
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }

  function t(key, params) {
    const value = lang === "en" && Object.hasOwn(EN, key) ? EN[key] : key;
    return typeof value === "function" ? value(params || {}) : format(value, params);
  }

  const locale = () => (lang === "en" ? "en-US" : "tr-TR");

  // The static markup is captured once, before app.js renders anything, so switching back and forth always
  // starts from the Turkish original.
  const textOriginals = new Map();
  const attrOriginals = new Map();
  const htmlOriginals = new Map();

  function capture(root) {
    for (const element of root.querySelectorAll("[data-i18n-html]")) htmlOriginals.set(element, element.innerHTML);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent || parent.closest("script, style, code, [data-i18n-html], [data-i18n-skip]")) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    while (walker.nextNode()) textOriginals.set(walker.currentNode, walker.currentNode.nodeValue);
    for (const element of root.querySelectorAll(ATTRIBUTES.map((name) => `[${name}]`).join(","))) {
      if (element.closest("[data-i18n-skip]")) continue;
      const values = {};
      for (const name of ATTRIBUTES) if (element.hasAttribute(name)) values[name] = element.getAttribute(name);
      attrOriginals.set(element, values);
    }
  }

  function translateText(original) {
    const key = original.trim();
    if (!key) return original;
    const start = original.slice(0, original.indexOf(key));
    const end = original.slice(original.indexOf(key) + key.length);
    return start + t(key) + end;
  }

  function applyStatic() {
    document.documentElement.lang = lang;
    for (const [node, original] of textOriginals) {
      if (node.isConnected) node.nodeValue = translateText(original);
    }
    for (const [element, values] of attrOriginals) {
      if (!element.isConnected) continue;
      for (const [name, original] of Object.entries(values)) element.setAttribute(name, t(original));
    }
    for (const [element, original] of htmlOriginals) {
      if (!element.isConnected) continue;
      const id = element.dataset.i18nHtml;
      element.innerHTML = lang === "en" && Object.hasOwn(EN_HTML, id) ? EN_HTML[id] : original;
    }
    for (const button of document.querySelectorAll("[data-lang]")) {
      button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
    }
  }

  function setLang(next) {
    if (!LANGS[next] || next === lang) return;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* not persisted; still applies to this page */ }
    applyStatic();
    window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  function init() {
    capture(document.body);
    applyStatic();
    document.addEventListener("click", (event) => {
      const button = event.target.closest("[data-lang]");
      if (button) setLang(button.dataset.lang);
    });
  }

  window.i18n = { t, locale, setLang, getLang: () => lang, LANGS, DEFAULT_LANG };
  window.t = t;
  // Loaded at the end of <body>, right before app.js, so all static markup is already parsed.
  init();
